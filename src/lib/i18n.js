const DICTS = { es: ES, en: EN }
export const LANGS = [
  ['es', 'Español'],
  ['en', 'English'],
]

// Idioma efectivo: el guardado, o inglés si el sistema lo está, o español.
export function detectLang() {
  try {
    const saved = localStorage.getItem('oficina-lang')
    if (DICTS[saved]) return saved
  } catch {}
  // fuera del navegador (tests, node) no hay navigator: cae a español
  const sys = typeof navigator === 'undefined' ? '' : navigator.language || ''
  return sys.toLowerCase().startsWith('en') ? 'en' : 'es'
}

let current = detectLang()
export const getLang = () => current
export function setLang(l) {
  current = DICTS[l] ? l : 'es'
  try {
    localStorage.setItem('oficina-lang', current)
  } catch {}
}

export function t(key, vars) {
  const s = DICTS[current]?.[key] ?? ES[key] ?? key
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m))
}

